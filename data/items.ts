export function getRecipeResult(comp1: string, comp2: string): string | null {
  for (const [id, item] of Object.entries(COMPLETED_ITEMS)) {
    const [r1, r2] = item.recipe;
    if ((r1 === comp1 && r2 === comp2) || (r1 === comp2 && r2 === comp1)) {
      return id;
    }
  }
  return null;
}
